test('the chart range switches between 7 and 30 days', async ({ page }) => {
  await page.clock.install()
  await page.goto('/')
  await page.getByPlaceholder('min').fill('1')
  await page.getByRole('button', { name: 'Start focus' }).click()
  await page.clock.runFor(61_000)
  await page.getByRole('button', { name: 'Show chart' }).click()
  await expect(page.getByRole('dialog', { name: 'Focus chart' })).toBeVisible()
  await expect(page.locator('.focus-bar')).toHaveCount(7)
  await page.getByRole('button', { name: '30 days' }).click()
  await expect(page.locator('.focus-bar')).toHaveCount(30)
  await page.getByRole('button', { name: '12 weeks' }).click()
  await expect(page.locator('.focus-heat')).toBeVisible()
  await expect(page.locator('.focus-bar')).toHaveCount(0)
  await expect(page.locator('.focus-legend')).toHaveCount(0)
})

test('the chart popup closes with Escape and with a click outside', async ({ page }) => {
  await page.clock.install()
  await page.goto('/')
  await page.getByPlaceholder('min').fill('1')
  await page.getByRole('button', { name: 'Start focus' }).click()
  await page.clock.runFor(61_000)
  await page.getByRole('button', { name: 'Show chart' }).click()
  await expect(page.getByRole('dialog', { name: 'Focus chart' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', { name: 'Focus chart' })).toBeHidden()
  await page.getByRole('button', { name: 'Show chart' }).click()
  await page.mouse.click(20, 20)
  await expect(page.getByRole('dialog', { name: 'Focus chart' })).toBeHidden()
})
